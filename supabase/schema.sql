-- URL Saver for Supabase — database schema
-- Run this once in your project's SQL Editor:
-- https://supabase.com/dashboard/project/_/sql/new

create table if not exists public.saved_urls (
  id bigint generated by default as identity primary key,
  url text not null,
  title text,
  created_at timestamptz not null default now()
);

comment on table public.saved_urls is
  'Pages saved by the URL Saver Chrome extension.';

-- Row Level Security is the security boundary for the public anon key.
alter table public.saved_urls enable row level security;

-- The extension may insert links, but it cannot read rows back.
drop policy if exists "anon can insert saved URLs" on public.saved_urls;
create policy "anon can insert saved URLs"
  on public.saved_urls
  for insert
  to anon
  with check (true);

-- PostgREST needs table privileges in addition to RLS policies.
-- SELECT is granted so the connection test can query the table, but the
-- absence of a SELECT policy means the query always returns zero rows.
grant select, insert on table public.saved_urls to anon;
grant usage, select on sequence public.saved_urls_id_seq to anon;

